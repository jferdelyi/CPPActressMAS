#pragma once

#include <array>
#include <compare>
#include <cstddef>
#include <cstdint>
#include <cstring>
#include <functional>
#include <optional>
#include <ostream>
#include <string>
#include <string_view>
#include <type_traits>

#include <nlohmann/json_fwd.hpp>

/**
 * CPPActressMAS
 */
namespace cam {

	/**
	 * Identifier of an agent: at most CAPACITY characters kept in place, so that it is copied, compared and
	 * hashed as two machine words. The identifiers generated by the framework have exactly CAPACITY base62
	 * characters (about 89 random bits); shorter ones are accepted, for instance "ext" for a sender outside the
	 * environments.
	 */
	class AgentId final {
		public:
			/**
			 * Most characters of an identifier.
			 */
			static constexpr std::size_t CAPACITY = 15;

		private:
			/**
			 * Characters, the unused ones set to zero so that two identifiers compare as words.
			 */
			std::array<char, CAPACITY> m_chars{};

			/**
			 * Number of characters.
			 */
			std::uint8_t m_length = 0;

			/**
			 * The 16 bytes of the identifier as two words.
			 * @param p_words Receives the words
			 */
			void words(std::uint64_t (&p_words)[2]) const noexcept {
				std::memcpy(p_words, this, sizeof(p_words));
			}

		public:
			/**
			 * Empty identifier (no agent).
			 */
			AgentId() = default;

			/**
			 * Identifier from a string literal, checked when compiling: "ext" can be written where an identifier is
			 * expected, and a literal longer than CAPACITY characters does not compile.
			 * @param p_id The literal
			 */
			template<std::size_t N>
			consteval AgentId(const char (&p_id)[N]) {
				static_assert(N - 1 <= CAPACITY, "an agent identifier has at most 15 characters");
				for (std::size_t i = 0; i + 1 < N; i++) {
					m_chars[i] = p_id[i];
				}
				m_length = static_cast<std::uint8_t>(N - 1);
			}

			/**
			 * Identifier from its text.
			 * @param p_id The text, at most CAPACITY characters
			 * @throw std::invalid_argument If the text is longer
			 */
			explicit AgentId(std::string_view p_id);

			/**
			 * Identifier from a text received from elsewhere, without exception.
			 * @param p_id The text
			 * @return The identifier, or nothing if the text is longer than CAPACITY characters
			 */
			[[nodiscard]] static std::optional<AgentId> parse(std::string_view p_id) noexcept;

			/**
			 * New random identifier of CAPACITY base62 characters. Thread-safe.
			 * @return The identifier
			 */
			[[nodiscard]] static AgentId generate();

			/**
			 * The characters.
			 * @return A view on the characters, valid as long as the identifier
			 */
			[[nodiscard]] std::string_view view() const noexcept { return {m_chars.data(), m_length}; }

			/**
			 * The characters as a string.
			 * @return The string
			 */
			[[nodiscard]] std::string str() const { return std::string(view()); }

			/**
			 * Number of characters.
			 * @return The number of characters
			 */
			[[nodiscard]] std::size_t size() const noexcept { return m_length; }

			/**
			 * True for the empty identifier.
			 * @return True if empty
			 */
			[[nodiscard]] bool empty() const noexcept { return m_length == 0; }

			/**
			 * Hash of the identifier: its two words mixed by multiplications and shifts.
			 * @return The hash
			 */
			[[nodiscard]] std::size_t hash() const noexcept {
				std::uint64_t l_words[2];
				words(l_words);
				std::uint64_t l_hash = l_words[0] ^ (l_words[1] * 0x9E3779B97F4A7C15ULL);
				l_hash ^= l_hash >> 32;
				l_hash *= 0xD6E8FEB86659FD93ULL;
				l_hash ^= l_hash >> 32;
				return static_cast<std::size_t>(l_hash);
			}

			/**
			 * Two identifiers are equal if they have the same characters.
			 * @param p_left An identifier
			 * @param p_right Another identifier
			 * @return True if equal
			 */
			friend bool operator==(const AgentId& p_left, const AgentId& p_right) noexcept {
				std::uint64_t l_left[2];
				std::uint64_t l_right[2];
				p_left.words(l_left);
				p_right.words(l_right);
				return l_left[0] == l_right[0] && l_left[1] == l_right[1];
			}

			/**
			 * Order of the characters, like the strings.
			 * @param p_left An identifier
			 * @param p_right Another identifier
			 * @return The order
			 */
			friend std::strong_ordering operator<=>(const AgentId& p_left, const AgentId& p_right) noexcept {
				return p_left.view() <=> p_right.view();
			}

			/**
			 * An identifier equals a text with the same characters.
			 * @param p_left An identifier
			 * @param p_right A text
			 * @return True if equal
			 */
			friend bool operator==(const AgentId& p_left, std::string_view p_right) noexcept {
				return p_left.view() == p_right;
			}

			/**
			 * An identifier equals a string literal with the same characters (exact match, no conversion).
			 * @param p_left An identifier
			 * @param p_right A literal
			 * @return True if equal
			 */
			template<std::size_t N>
			friend bool operator==(const AgentId& p_left, const char (&p_right)[N]) noexcept {
				return p_left.view() == std::string_view(p_right, N - 1);
			}
	};

	static_assert(sizeof(AgentId) == 16, "an agent identifier is two machine words");
	static_assert(std::is_trivially_copyable_v<AgentId>, "an agent identifier is copied as bytes");

	/**
	 * Write the characters of an identifier.
	 * @param p_stream The stream
	 * @param p_id The identifier
	 * @return The stream
	 */
	std::ostream& operator<<(std::ostream& p_stream, const AgentId& p_id);

	/**
	 * An identifier is a JSON string.
	 * @param p_json Receives the string
	 * @param p_id The identifier
	 */
	void to_json(nlohmann::json& p_json, const AgentId& p_id);

	/**
	 * Identifier from a JSON string.
	 * @param p_json The string, at most AgentId::CAPACITY characters
	 * @param p_id Receives the identifier
	 * @throw std::invalid_argument If the string is longer
	 */
	void from_json(const nlohmann::json& p_json, AgentId& p_id);

} // namespace cam

/**
 * Hash of the agent identifiers, for the standard containers.
 */
template<>
struct std::hash<cam::AgentId> {
	std::size_t operator()(const cam::AgentId& p_id) const noexcept { return p_id.hash(); }
};
